    /** Source lines (comments removed) of the erasable assignments, in order. */
    public static final List<String> SOURCE_PARTS = List.of(PART_0, PART_1, PART_2, PART_3, PART_4);

    private static final Map<String, Integer> ADDRESSES = new HashMap<>();
    private static final Map<String, String> PENDING = new HashMap<>();
    private static final Pattern OFFSET = Pattern.compile("^(.+?)\\s*([+-])\\s*([0-9]+D?)$");
    /** Fixed register addresses used as operands of EQUALS. */
    private static final Map<String, Integer> REGISTERS = Map.of("A", 0, "L", 1, "Q", 2, "Z", 5);

    static {
        int loc = 0;
        List<String[]> deferred = new ArrayList<>();
        for (String part : SOURCE_PARTS) {
            for (String line : part.split("\n")) {
                if (line.isBlank()) {
                    continue;
                }
                boolean labelled = !Character.isWhitespace(line.charAt(0));
                String[] t = line.trim().split("\\s+", labelled ? 3 : 2);
                String label = labelled ? t[0] : null;
                String op = labelled ? (t.length > 1 ? t[1] : "") : t[0];
                String arg = labelled ? (t.length > 2 ? t[2].trim() : "") : (t.length > 1 ? t[1].trim() : "");
                switch (op) {
                    case "SETLOC" -> loc = number(arg);
                    case "ERASE" -> {
                        if (arg.contains(" - ")) {          // ERASE a - b: absolute range, location counter unchanged
                            if (label != null) {
                                ADDRESSES.put(label, number(arg.split(" - ")[0]));
                            }
                            break;
                        }
                        if (label != null) {
                            ADDRESSES.put(label, loc);
                        }
                        loc += 1 + (arg.isEmpty() ? 0 : number(arg.replace("+", "").trim()));
                    }
                    case "EQUALS", "=" -> {
                        if (label != null) {
                            deferred.add(new String[] {label, arg});
                        }
                    }
                    default -> { }
                }
            }
        }
        // resolve EQUALS definitions (may chain; iterate to a fixed point)
        for (String[] d : deferred) {
            PENDING.put(d[0], d[1]);
        }
        for (String[] d : deferred) {
            ADDRESSES.put(d[0], eval(d[1], 0));
        }
    }

    /** Parses an AGC number: trailing D means decimal, otherwise octal. */
    private static int number(String s) {
        s = s.trim();
        if (s.endsWith("D")) {
            return Integer.parseInt(s.substring(0, s.length() - 1));
        }
        return Integer.parseInt(s, 8);
    }

    private static boolean isNumber(String s) {
        return s.matches("[0-7]+|[0-9]+D");
    }

    private static int eval(String expr, int depth) {
        expr = expr.trim();
        if (isNumber(expr)) {
            return number(expr);
        }
        Matcher m = OFFSET.matcher(expr);
        if (m.matches() && !isNumber(expr)) {
            int base = eval(m.group(1), depth + 1);
            int off = number(m.group(3));
            return m.group(2).equals("-") ? base - off : base + off;
        }
        if (REGISTERS.containsKey(expr)) {
            return REGISTERS.get(expr);
        }
        Integer a = ADDRESSES.get(expr);
        if (a != null) {
            return a;
        }
        String p = PENDING.get(expr);
        if (p != null && depth < 50) {
            int v = eval(p, depth + 1);
            ADDRESSES.put(expr, v);
            return v;
        }
        return 0;
    }

    /** Returns the erasable address of a symbol, or an expression such as "STATE +14D". */
    public static int address(String symbolOrExpression) {
        return eval(symbolOrExpression, 0);
    }

    /** True if the symbol was defined by the erasable assignments. */
    public static boolean isDefined(String symbol) {
        return ADDRESSES.containsKey(symbol);
    }

    /** All defined symbols with their addresses. */
    public static Map<String, Integer> symbols() {
        return java.util.Collections.unmodifiableMap(ADDRESSES);
    }
